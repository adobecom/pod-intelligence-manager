import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(scriptDir, "..");
const schemaPath = path.join(packageDir, "contracts", "memory-contracts.v1.schema.json");
const fixturePath = path.join(packageDir, "contracts", "memory-contract-fixtures.v1.json");
const tsPath = path.join(packageDir, "src", "types", "memory-contracts.generated.ts");
const pythonPath = path.join(packageDir, "contracts", "generated", "memory_contracts_v1.py");
const checkOnly = process.argv.includes("--check");

const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const fixtures = JSON.parse(fs.readFileSync(fixturePath, "utf8"));
const definitions = schema.$defs ?? {};

function referencedName(ref) {
  const prefix = "#/$defs/";
  if (!ref.startsWith(prefix)) throw new Error(`Unsupported external schema reference: ${ref}`);
  return ref.slice(prefix.length);
}

function tsType(node, depth = 0) {
  if (!node || typeof node !== "object") return "unknown";
  if (node.$ref) return referencedName(node.$ref);
  if (Object.prototype.hasOwnProperty.call(node, "const")) return JSON.stringify(node.const);
  if (Array.isArray(node.enum)) return node.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (Array.isArray(node.oneOf)) return node.oneOf.map((item) => tsType(item, depth)).join(" | ");
  if (Array.isArray(node.anyOf)) return node.anyOf.map((item) => tsType(item, depth)).join(" | ");
  if (Array.isArray(node.type)) {
    return node.type.map((type) => tsType({ ...node, type }, depth)).join(" | ");
  }
  if (node.type === "string") return "string";
  if (node.type === "integer" || node.type === "number") return "number";
  if (node.type === "boolean") return "boolean";
  if (node.type === "null") return "null";
  if (node.type === "array") return `Array<${tsType(node.items ?? {}, depth)}>`;
  if (node.type === "object" || node.properties || node.additionalProperties) {
    const properties = node.properties ?? {};
    const required = new Set(node.required ?? []);
    const names = Object.keys(properties);
    if (names.length === 0 && node.additionalProperties && node.additionalProperties !== true) {
      return `Record<string, ${tsType(node.additionalProperties, depth + 1)}>`;
    }
    if (names.length === 0) return "Record<string, unknown>";
    const indent = "  ".repeat(depth + 1);
    const closing = "  ".repeat(depth);
    const fields = names.map((name) => {
      const optional = required.has(name) ? "" : "?";
      return `${indent}${JSON.stringify(name)}${optional}: ${tsType(properties[name], depth + 1)};`;
    });
    return `{\n${fields.join("\n")}\n${closing}}`;
  }
  return "unknown";
}

function pythonType(node) {
  if (!node || typeof node !== "object") return "Any";
  if (node.$ref) return referencedName(node.$ref);
  if (Object.prototype.hasOwnProperty.call(node, "const")) return `Literal[${JSON.stringify(node.const)}]`;
  if (Array.isArray(node.enum)) return `Literal[${node.enum.map((value) => JSON.stringify(value)).join(", ")}]`;
  if (Array.isArray(node.oneOf)) return node.oneOf.map(pythonType).join(" | ");
  if (Array.isArray(node.anyOf)) return node.anyOf.map(pythonType).join(" | ");
  if (Array.isArray(node.type)) return node.type.map((type) => pythonType({ ...node, type })).join(" | ");
  if (node.type === "string") return "str";
  if (node.type === "integer") return "int";
  if (node.type === "number") return "float";
  if (node.type === "boolean") return "bool";
  if (node.type === "null") return "None";
  if (node.type === "array") return `list[${pythonType(node.items ?? {})}]`;
  if (node.type === "object" || node.properties || node.additionalProperties) {
    if (node.additionalProperties && node.additionalProperties !== true && !node.properties) {
      return `dict[str, ${pythonType(node.additionalProperties)}]`;
    }
    return "dict[str, Any]";
  }
  return "Any";
}

const banner = "// Generated by scripts/generate-memory-contracts.mjs. Do not edit by hand.";
const typeNames = Object.keys(definitions);
const tsTypes = typeNames.map((name) => `export type ${name} = ${tsType(definitions[name])};`).join("\n\n");
const tsTypeMap = typeNames.map((name) => `  ${JSON.stringify(name)}: ${name};`).join("\n");
const ts = `${banner}\n\nexport const MEMORY_CONTRACT_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\n\nexport const MEMORY_CONTRACT_FIXTURES = ${JSON.stringify(fixtures, null, 2)} as const;\n\nexport type MemoryContractName = keyof typeof MEMORY_CONTRACT_SCHEMA.$defs;\n\n${tsTypes}\n\nexport interface MemoryContractTypeMap {\n${tsTypeMap}\n}\n`;

const pythonClasses = typeNames.map((name) => {
  const definition = definitions[name];
  if (definition.type !== "object" || !definition.properties) {
    return `${name}: TypeAlias = ${pythonType(definition)}`;
  }
  const required = new Set(definition.required ?? []);
  const fields = Object.entries(definition.properties).map(([field, child]) => {
    const valueType = pythonType(child);
    return `    ${field}: ${required.has(field) ? valueType : `NotRequired[${valueType}]`}`;
  });
  return `class ${name}(TypedDict):\n${fields.length > 0 ? fields.join("\n") : "    pass"}`;
}).join("\n\n");
const python = `# Generated by scripts/generate-memory-contracts.mjs. Do not edit by hand.\nfrom __future__ import annotations\n\nimport json\nfrom typing import Any, Literal, TypeAlias, TypedDict\n\ntry:\n    from typing import NotRequired\nexcept ImportError:  # Python 3.10 compatibility\n    from typing_extensions import NotRequired\n\n${pythonClasses}\n\nMEMORY_CONTRACT_FIXTURES: dict[str, Any] = json.loads(r'''${JSON.stringify(fixtures)}''')\n`;

function writeOrCheck(target, content) {
  if (checkOnly) {
    const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
    if (existing !== content) throw new Error(`Generated contract artifact is stale: ${path.relative(packageDir, target)}`);
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
}

writeOrCheck(tsPath, ts);
writeOrCheck(pythonPath, python);
